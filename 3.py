#вводим коллекцию
a = [29, 10, 14, 37, 13]
#вводим новую коллекцию, в которую будем добавлять минимальные элементы 
b = []
#совершаем сортировку выбором
while (len(a)>0):
    min = a[0]
    for i in range(0,len(a)) :
        if a[i] < min :
           min = a[i]
    a.remove(min)
    b.append(min)
    print("Промежуточный результат старой коллекции: ", a)
    print("Промежуточный результат новой коллекции: ", b)
#выводим результат
print("Результат старой коллекции: ",a)
print("Результат новой коллекции: ",b)